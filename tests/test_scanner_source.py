def test_fetch_repo_tree_parses_paths():
    def fake(url, token):
        assert "git/trees" in url
        return {"tree": [{"path": "app/robots.ts", "type": "blob"},
                         {"path": "public", "type": "tree"},
                         {"path": "public/llms.txt", "type": "blob"}]}
    paths = fetch_repo_tree("owner/name", "tok", fetch=fake)
    assert "app/robots.ts" in paths and "public/llms.txt" in paths
    assert "public" not in paths  # trees (dirs) excluded, blobs only


