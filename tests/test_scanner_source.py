"""Source-code audit (pipeline/scanner/source_audit.py) — pure analyzer, offline."""
from pipeline.scanner.source_audit import analyze_source, fetch_repo_files, fetch_repo_tree


def test_tree_route_checks():
    tree = ["app/layout.tsx", "app/robots.ts", "app/sitemap.ts", "public/llms.txt", "middleware.ts"]
    by = {r["what"]: r for r in analyze_source({}, tree)}
    assert by["Source: robots.txt"]["severity"] == "ok"      # satisfied by app/robots.ts route
    assert by["Source: sitemap.xml"]["severity"] == "ok"     # satisfied by app/sitemap.ts route
    assert by["Source: llms.txt"]["severity"] == "ok"        # AEO
    assert by["Source: router"]["detail"] == "app router"
    assert by["Source: middleware"]["severity"] == "ok"


def test_tree_missing_seo_files():
    files = {"package.json": '{"dependencies":{"next":"14"}}'}
